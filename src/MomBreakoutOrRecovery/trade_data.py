# =========================================================
# DETERMINE ANALYSIS DATE
# =========================================================

def get_latest_trading_date(data):
    """
    Determine the latest valid trading date available
    in the downloaded Yahoo Finance data.

    The analysis date is NOT today's calendar date.

    It is the latest date for which market data actually
    exists in the downloaded dataset.

    Example:

        Today       : Saturday, 29-Aug-2026
        Latest data : Friday, 28-Aug-2026

        Analysis Date = 28-Aug-2026
    """

    if data is None or data.empty:

        raise RuntimeError(
            "Market data is empty. "
            "Cannot determine analysis date."
        )

    # -----------------------------------------------------
    # The index contains the trading dates.
    # -----------------------------------------------------

    valid_dates = pd.DatetimeIndex(
        data.index
    ).dropna()

    if len(valid_dates) == 0:

        raise RuntimeError(
            "No valid trading dates found "
            "in market data."
        )

    # -----------------------------------------------------
    # Latest date actually returned by Yahoo.
    # -----------------------------------------------------

    latest_date = valid_dates.max()

    return latest_date


# =========================================================
# MULTI-YEAR HISTORICAL DATA
# =========================================================

def get_historical_market_data_for_symbols(
    symbols,
    period="5y"
):
    """
    Download multi-year OHLCV data for backtesting.
    """

    data = yf.download(
        symbols,
        period=period,
        interval="1d",
        auto_adjust=False,
        progress=True,
        group_by="column",
        threads=True
    )

    valid_symbols = []
    invalid_symbols = []

    for symbol in symbols:

        try:

            close_prices = (
                data["Close"][symbol]
            )

            if close_prices.dropna().empty:

                invalid_symbols.append(symbol)

            else:

                valid_symbols.append(symbol)

        except (KeyError, TypeError):

            invalid_symbols.append(symbol)

    print()
    print(
        "Historical data period:",
        period
    )

    print(
        "Requested symbols:",
        len(symbols)
    )

    print(
        "Valid symbols:",
        len(valid_symbols)
    )

    print(
        "Invalid symbols:",
        len(invalid_symbols)
    )

    return data, valid_symbols


# =========================================================
# CURRENT MARKET DATA FOR ALL SYMBOLS
# =========================================================

def get_market_data_for_symbols(symbols):
    """
    Download 1 year of daily OHLCV data.

    Returns:

        data
        valid_symbols
        analysis_date

    analysis_date is the latest trading date actually
    available in the downloaded Yahoo Finance dataset.
    """

    data = yf.download(
        symbols,
        period="1y",
        interval="1d",
        auto_adjust=False,
        progress=True,
        group_by="column",
        threads=True
    )

    # -----------------------------------------------------
    # Validate data
    # -----------------------------------------------------

    if data is None or data.empty:

        raise RuntimeError(
            "Yahoo Finance returned no market data."
        )

    # -----------------------------------------------------
    # Determine latest available trading date
    # -----------------------------------------------------

    analysis_date = get_latest_trading_date(
        data
    )

    # -----------------------------------------------------
    # Validate symbols
    # -----------------------------------------------------

    valid_symbols = []
    invalid_symbols = []

    for symbol in symbols:

        try:

            close_prices = (
                data["Close"][symbol]
            )

            if close_prices.dropna().empty:

                invalid_symbols.append(symbol)

            else:

                valid_symbols.append(symbol)

        except (KeyError, TypeError):

            invalid_symbols.append(symbol)

    # -----------------------------------------------------
    # Print download information
    # -----------------------------------------------------

    print()

    print(
        "Requested symbols:",
        len(symbols)
    )

    print(
        "Valid symbols:",
        len(valid_symbols)
    )

    print(
        "Invalid symbols:",
        len(invalid_symbols)
    )

    print()

    print(
        "Latest available trading date:",
        analysis_date.strftime("%d-%b-%Y")
    )

    print(
        "Analysis date:",
        analysis_date.strftime("%d-%b-%Y")
    )

    return (
        data,
        valid_symbols,
        analysis_date
    )
