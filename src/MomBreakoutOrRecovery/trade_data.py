import os
import pandas as pd
import yfinance as yf


UNIVERSE_FILE = "universe.py"

NIFTY500_URL = (
    "https://www.niftyindices.com/IndexConstituent/"
    "ind_nifty500list.csv"
)

WIKIPEDIA_URL = "https://en.wikipedia.org/wiki/NIFTY_500"


# =========================================================
# DYNAMIC NIFTY 500 UNIVERSE
# =========================================================

def get_nifty500_symbols():
    """
    Fetch the CURRENT Nifty 500 constituents.

    Priority:
        1. Official Nifty Indices CSV
        2. Wikipedia fallback

    Returns:
        List of Yahoo Finance symbols ending in .NS
    """

    print()
    print("=" * 64)
    print("UPDATING NIFTY 500 UNIVERSE")
    print("=" * 64)

    # -----------------------------------------------------
    # Method 1 — Official Nifty 500 CSV
    # -----------------------------------------------------

    try:

        print("Source : Official Nifty Indices")

        df = pd.read_csv(
            NIFTY500_URL,
            storage_options={
                "User-Agent": "Mozilla/5.0"
            }
        )

        symbol_column = None

        for column in ["Symbol", "SYMBOL", "symbol"]:

            if column in df.columns:

                symbol_column = column

                break

        if symbol_column is None:

            raise ValueError(
                "Could not find Symbol column."
            )

        symbols = (
            df[symbol_column]
            .dropna()
            .astype(str)
            .str.strip()
            .str.upper()
            .tolist()
        )

        symbols = [
            symbol if symbol.endswith(".NS")
            else symbol + ".NS"
            for symbol in symbols
            if symbol
        ]

        symbols = sorted(set(symbols))

        if len(symbols) >= 400:

            print(
                f"Current Nifty 500 constituents : "
                f"{len(symbols)}"
            )

            return symbols

    except Exception as e:

        print(
            "Official Nifty 500 download failed:"
        )

        print(f"Reason: {e}")

    # -----------------------------------------------------
    # Method 2 — Wikipedia fallback
    # -----------------------------------------------------

    try:

        print()
        print("Trying Wikipedia fallback...")

        tables = pd.read_html(
            WIKIPEDIA_URL
        )

        for table in tables:

            for column in table.columns:

                values = (
                    table[column]
                    .dropna()
                    .astype(str)
                    .str.strip()
                )

                candidate_count = sum(
                    values.str.match(
                        r"^[A-Za-z0-9&._-]+$"
                    )
                )

                if candidate_count < 400:

                    continue

                symbols = [
                    value.upper()
                    for value in values
                    if (
                        len(value) <= 30
                        and value.lower()
                        not in {
                            "symbol",
                            "company name"
                        }
                    )
                ]

                symbols = [
                    symbol if symbol.endswith(".NS")
                    else symbol + ".NS"
                    for symbol in symbols
                ]

                symbols = sorted(set(symbols))

                if len(symbols) >= 400:

                    print(
                        f"Current Nifty 500 constituents : "
                        f"{len(symbols)}"
                    )

                    return symbols

    except Exception as e:

        print(
            "Wikipedia fallback failed:"
        )

        print(f"Reason: {e}")

    raise RuntimeError(
        "Could not obtain current Nifty 500 universe."
    )


