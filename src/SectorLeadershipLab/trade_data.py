def get_market_data(symbol):

    """
    Download 1 year of daily market data.
    """

    data = yf.download(
        symbol,
        period="1y",
        interval="1d",
        auto_adjust=False,
        progress=False
    )

    return data


# =========================================================
# MULTI-YEAR HISTORICAL DATA
# =========================================================

def get_historical_market_data_for_symbols(
    symbols,
    period="5y"
):

    """
    Download multi-year OHLCV data for backtesting.
    """

    data = yf.download(
        symbols,
        period=period,
        interval="1d",
        auto_adjust=False,
        progress=True,
        group_by="column",
        threads=True
    )

    valid_symbols = []
    invalid_symbols = []

    for symbol in symbols:

        try:

            close_prices = data["Close"][symbol]

            if close_prices.dropna().empty:
                invalid_symbols.append(symbol)

            else:
                valid_symbols.append(symbol)

        except (KeyError, TypeError):

            invalid_symbols.append(symbol)

    print()
    print(
        "Historical data period:",
        period
    )

    print(
        "Requested symbols:",
        len(symbols)
    )

    print(
        "Valid symbols:",
        len(valid_symbols)
    )

    print(
        "Invalid symbols:",
        len(invalid_symbols)
    )

    return data, valid_symbols


