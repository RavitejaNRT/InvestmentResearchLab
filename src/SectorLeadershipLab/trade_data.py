# =========================================================
# PUBLIC FUNCTION
# =========================================================

def refresh_nifty500_universe():
    """
    Download the current Nifty 500 membership
    and regenerate universe.py.
    """

    symbols = get_nifty500_symbols()

    update_universe_file(symbols)

    return symbols


